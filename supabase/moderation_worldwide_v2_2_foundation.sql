-- Index B-tree : la fonction V2.2 cherche des candidats exacts normalisés,
-- au lieu de parcourir toute la table à chaque message.
create index if not exists
  idx_moderation_global_lexicon_normalized_active
on public.moderation_global_lexicon (
  normalized_term
)
where active = true;


create index if not exists
  idx_moderation_global_lexicon_action_active
on public.moderation_global_lexicon (
  action,
  normalized_term
)
where active = true;


create index if not exists
  idx_moderation_global_lexicon_language
on public.moderation_global_lexicon (
  language_code
);


-- ============================================================================
-- RPC DE MATCH RAPIDE
--
-- L'Edge Function envoie uniquement les mots / expressions possibles du
-- message. PostgreSQL fait alors des recherches exactes via l'index.
--
-- Pas d'accès client : service_role uniquement.
-- ============================================================================

create or replace function public.project_xp_match_global_lexicon(
  p_candidates text[]
)
returns table (
  term text,
  normalized_term text,
  language_code text,
  action text
)

language sql

stable

security definer

set search_path =
  public

as $$

  select
    l.term,
    l.normalized_term,
    l.language_code,
    l.action

  from
    public.moderation_global_lexicon as l

  where
    l.active = true

    and l.normalized_term = any(
      coalesce(
        p_candidates,
        array[]::text[]
      )
    )

  order by
    case l.action
      when 'hard_block' then 0
      when 'context' then 1
      else 2
    end,

    char_length(
      l.normalized_term
    ) desc

  limit 100;

$$;


revoke all
on function public.project_xp_match_global_lexicon(text[])
from public,
     anon,
     authenticated;


grant execute
on function public.project_xp_match_global_lexicon(text[])
to service_role;


