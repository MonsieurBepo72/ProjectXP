-- ============================================================================
-- LEXIQUE MONDIAL
--
-- action :
--
--   context
--     Terme potentiellement problématique.
--     Il ne bloque PAS tout seul.
--     Il renforce la décision de la modération contextuelle.
--
--   hard_block
--     Terme validé manuellement comme suffisamment grave et non ambigu.
--     Blocage direct côté serveur.
--
--   vulgarity
--     Terme grossier / vulgaire, conservé pour un futur filtre utilisateur,
--     mais pas utilisé comme interdiction de sécurité.
-- ============================================================================

create table if not exists public.moderation_global_lexicon (
  id bigint generated by default as identity
    primary key,

  source_key text not null
    references public.moderation_lexicon_sources(source_key)
    on delete cascade,

  language_code text not null,

  term text not null,

  normalized_term text not null,

  action text not null
    default 'context',

  active boolean not null
    default true,

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now(),

  constraint moderation_global_lexicon_action_check
    check (
      action in (
        'context',
        'hard_block',
        'vulgarity'
      )
    ),

  constraint moderation_global_lexicon_unique_term
    unique (
      source_key,
      language_code,
      normalized_term
    )
);


alter table public.moderation_global_lexicon
enable row level security;


-- Le téléphone n'a pas besoin de télécharger 50 000+ termes.
